import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { z } from "zod";
import type { ModelConfigRow, ModelId, ModelRegistryEntry } from "../../shared/contracts.js";
import { getSetting } from "../persistence/settings-store.js";

const entry = z.object({ id: z.string().min(1), taskTypes: z.array(z.enum(["vision", "draft", "code"])).min(1).optional(), runtime: z.enum(["mlx-lm", "llama-server", "ollama"]), baseUrl: z.string().url(), model: z.string().min(1), capabilities: z.array(z.enum(["text", "image-input", "structured-output", "code-generation"])), requestTimeoutMs: z.number().int().positive().max(600000), healthPath: z.literal("/models"), enabled: z.boolean(), fallbackOnly: z.boolean().optional(), toolCallingFormat: z.enum(["native", "json"]).optional(), temperature: z.number().min(0).max(2).optional(), contextLength: z.number().int().positive().max(128000).optional(), maxOutputTokens: z.number().int().positive().max(128000).optional() }).strict();
const config = z.object({ $comment: z.string().optional(), models: z.array(entry).min(1) }).strict();


let configuredModelsPath: string | null = null;

/** Called from `initBackend` with the Electron-provided config. */
export function configureModels(options: { modelsPath: string | null }): void {
  configuredModelsPath = options.modelsPath;
}

export function defaultModelsPath(): string {
  if (configuredModelsPath) return configuredModelsPath;
  const fromEnv = process.env.WORKBENCH_MODELS_PATH;
  if (fromEnv) return path.resolve(fromEnv);
  return path.resolve(process.cwd(), "config", "models.json");
}

export function sanitizeHost(host: string): string {
  let cleaned = (host || "").trim();
  cleaned = cleaned.replace(/^https?:\/\//i, "");
  cleaned = cleaned.replace(/\/.*$/, "");
  if (cleaned.includes(":") && !cleaned.includes("[")) {
    const parts = cleaned.split(":");
    if (parts.length === 2 && /^\d+$/.test(parts[1])) {
      cleaned = parts[0];
    }
  }
  return cleaned || "127.0.0.1";
}

export function buildRegistryFromRows(rows: ModelConfigRow[]): ModelRegistryEntry[] {
  // Preserve endpoint-specific transport and generation settings when restoring
  // the same selected endpoint from onboarding. Selection still comes from rows.
  let profiles: ModelRegistryEntry[] = [];
  try { profiles = Array.from(loadRegistry().values()); } catch { /* No file profile configured. */ }
  const eligible = rows.filter((row) => row.role !== "embedding" && row.modelName?.trim());
  const primaryRows = eligible.filter((row) => row.role === "primary");
  const roleOrder: Array<ModelConfigRow["role"]> = ["draft", "vision", "coding"];
  const roleRows = roleOrder.flatMap((role) => eligible.filter((row) => row.role === role));
  // `primary` is accepted for settings written by earlier app versions. New
  // onboarding saves the three user-facing roles. Draft is the default route.
  const candidates = roleRows.length > 0 ? roleRows : primaryRows;
  const seen = new Set<string>();
  const primaryEntries: ModelRegistryEntry[] = candidates.filter((row) => {
    const key = `${sanitizeHost(row.host)}:${row.port || 11434}/${row.modelName.toLowerCase()}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  }).map((row, index) => {
    const host = sanitizeHost(row.host);
    const port = row.port || 11434;
    const baseUrl = `http://${host}:${port}/v1`;
    const profile = profiles.find(candidate => candidate.model === row.modelName && candidate.baseUrl.replace(/\/$/, "") === baseUrl);
    return {
      id: index === 0 ? "primary-model" : `model-${index + 1}`, runtime: "ollama",
      baseUrl, model: row.modelName,
      capabilities: profile?.capabilities ?? (candidates.some(candidate => candidate.role === "vision" && candidate.modelName.toLowerCase() === row.modelName.toLowerCase() && sanitizeHost(candidate.host) === host && (candidate.port || 11434) === port) ? ["text", "image-input", "structured-output"] : ["text", "structured-output", "code-generation"]),
      requestTimeoutMs: 300000, healthPath: "/models", enabled: true,
      contextLength: row.contextLength || 8192,
      maxOutputTokens: profile?.maxOutputTokens ?? (row.contextLength || 8192),
      ...(profile?.toolCallingFormat ? { toolCallingFormat: profile.toolCallingFormat } : {}),
      ...(profile?.temperature !== undefined ? { temperature: profile.temperature } : {}),
    };
  });
  const auxiliary = profiles.filter(profile => profile.fallbackOnly && !primaryEntries.some(primary => primary.id === profile.id || (primary.model === profile.model && primary.baseUrl === profile.baseUrl)));
  return [...primaryEntries, ...auxiliary];
}

export function writeRegistryToFile(entries: ModelRegistryEntry[], filePath?: string): void {
  const target = filePath ?? defaultModelsPath();
  const payload = {
    $comment: "Generated by Sovereign Workbench Onboarding.",
    models: entries,
  };
  writeFileSync(target, JSON.stringify(payload, null, 2), "utf8");
}

export function defaultLocalRegistry(): Map<ModelId, ModelRegistryEntry> {
  const entries = buildRegistryFromRows([
    { role: "draft", modelName: "qwen3:8b", host: "127.0.0.1", port: 11434, contextLength: 32768 },
  ]);
  return new Map(entries.map((e) => [e.id, e]));
}

export function loadProductionRegistryEntriesFromDb(dbModels?: ModelConfigRow[]): ModelRegistryEntry[] {
  let rows = dbModels;
  if (!rows) {
    try {
      rows = getSetting<ModelConfigRow[]>("configured_models");
    } catch {
      // In standalone tests where DB is not open
    }
  }

  if (rows && Array.isArray(rows) && rows.length > 0) {
    return buildRegistryFromRows(rows);
  }

  try { return Array.from(loadRegistry().values()); } catch { return Array.from(defaultLocalRegistry().values()); }
}

export function loadProductionRegistryFromDb(dbModels?: ModelConfigRow[]): Map<ModelId, ModelRegistryEntry> {
  const entries = loadProductionRegistryEntriesFromDb(dbModels);
  return new Map(entries.map((e) => [e.id, e]));
}


export function loadRegistry(filePath?: string): Map<ModelId, ModelRegistryEntry> {
  const resolved = filePath ?? defaultModelsPath();
  let text: string;
  try {
    text = readFileSync(resolved, "utf8");
  } catch {
    throw new Error(`models.json not found (tried: ${resolved})`);
  }
  const parsed = config.parse(JSON.parse(text));
  return new Map(parsed.models.map((model) => [model.id, model as ModelRegistryEntry]));
}

export function resolveModel(registry: Map<ModelId, ModelRegistryEntry>, modelId: ModelId, taskType?: string): ModelRegistryEntry {
  const model = registry.get(modelId);
  // Task type records request semantics. It does not route to a specialist endpoint.
  void taskType;
  if (!model || !model.enabled) throw new Error(`model unavailable: ${modelId}`);
  return model;
}
